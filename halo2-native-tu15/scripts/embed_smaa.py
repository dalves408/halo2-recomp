"""Embeds src/gpu/smaa/SMAA.hlsl (SMAA reference shader, MIT, iryoku/smaa) as a byte array:
src/gpu/smaa/smaa_hlsl.h. Run again after updating SMAA.hlsl."""
from pathlib import Path
d = Path(__file__).resolve().parent.parent / 'src' / 'gpu' / 'smaa'
b = (d / 'SMAA.hlsl').read_bytes()
rows = [', '.join(str(x) for x in b[i:i + 24]) for i in range(0, len(b), 24)]
(d / 'smaa_hlsl.h').write_text('/* Generated by scripts/embed_smaa.py from SMAA.hlsl; do not edit. */\n'
    'static const unsigned char smaa_hlsl_src[] = {\n' + ',\n'.join(rows) + '\n};\n', encoding='ascii')
print(len(b), 'bytes')
