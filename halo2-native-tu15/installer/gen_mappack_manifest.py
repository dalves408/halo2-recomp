"""Writes mappack_manifest.h: the files halo2_mappack takes from the player's Halo 2 Multiplayer Map Pack disc
(path on the disc, size, SHA-256), taken from the disc image itself.

    python installer/gen_mappack_manifest.py <Map Pack disc image>

Group 0 is the three map packs (Bonus, Killtacular, Maptacular), always installed; group 1 the disc's videos and
their preview pictures, installed only when the player asks for them. Only sizes and hashes are written: no game
data."""
import hashlib
import struct
import sys
from pathlib import Path

image = Path(sys.argv[1])
out = Path(__file__).with_name('mappack_manifest.h')

img = open(image, 'rb')
base = None
for off in (0, 0x18300000, 0x0FD90000, 0x02080000):
    img.seek(off + 32 * 2048)
    v = img.read(28)
    if v[:20] == b'MICROSOFT*XBOX*MEDIA':
        base = off
        root_sector, root_size = struct.unpack('<II', v[20:28])
        break
if base is None:
    sys.exit(f'{image} is not an Xbox disc image')
disc = {}


def walk(sector, size, prefix):
    img.seek(base + sector * 2048)
    d = img.read(size)

    def node(pos):
        if pos + 14 > len(d):
            return
        left, right, s, z, attr, nl = struct.unpack('<HHIIBB', d[pos:pos + 14])
        if left == 0xFFFF:
            return
        if left:
            node(left * 4)
        name = prefix + d[pos + 14:pos + 14 + nl].decode('latin-1')
        if attr & 0x10:
            walk(s, z, name + '/')
        else:
            disc[name] = (s, z)
        if right:
            node(right * 4)
    node(0)


walk(root_sector, root_size, '')


def sha(sector, size):
    img.seek(base + sector * 2048)
    h = hashlib.sha256()
    while size:
        b = img.read(min(size, 1 << 22))
        h.update(b)
        size -= len(b)
    return h.digest()


rows = []
for name in sorted(disc, key=str.lower):
    low = name.lower()
    if low.startswith('demos/dlc/0000000') and low.count('/') == 3:
        group = 0
    elif low.startswith('movies/') and (low.endswith('.sfd') or low.endswith('.txt')) and 'ddsfdplayer' not in low:
        group = 1
    elif low.startswith('videos/') and low.endswith('.bmp') and Path(low).stem in (
            'beach', 'interprev', 'sstest', 'announce', 'e3_2000'):
        group = 1
    else:
        continue
    s, z = disc[name]
    rows.append((name, z, sha(s, z), group))
    print(f'{group} {z:>12} {name}')

if sum(1 for r in rows if r[3] == 0) != 21:
    sys.exit('expected the 21 files of map packs 1-3')

with open(out, 'w', newline='\r\n') as f:
    f.write('/* generated by gen_mappack_manifest.py; do not edit. Sizes and SHA-256 only: no game data. */\n')
    f.write('/* Halo 2 Multiplayer Map Pack (World). group: 0 a map pack file, 1 a video or its preview picture */\n')
    f.write('static const struct { const char *path; unsigned long long size; unsigned char sha256[32]; int group; }'
            ' MP_MANIFEST[] = {\n')
    for name, z, h, g in rows:
        f.write(f'    {{ "{name}", {z}ULL, {{{",".join(str(b) for b in h)}}}, {g} }},\n')
    f.write('};\n#define MP_MANIFEST_COUNT ((int)(sizeof MP_MANIFEST / sizeof MP_MANIFEST[0]))\n')
print(out, len(rows), 'files')
