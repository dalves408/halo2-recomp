"""Writes manifest.h: every file the game reads (path, size, SHA-256) and where it comes from, taken from a known-good
game folder (the disc's files with title update 1.5 applied) and the disc image itself.

    python installer/gen_manifest.py <game folder> <disc image>

Files equal to the disc's are "disc" files; the others (default.xbe and downloader.xbe) are title update 1.5's and come
from the player's console. The disc's own default.xbe is pinned too: it tells the right disc from any other.
Only sizes and hashes are written: no game data."""
import hashlib
import struct
import sys
from pathlib import Path

folder, image = Path(sys.argv[1]), Path(sys.argv[2])


def sha(stream, size):
    h = hashlib.sha256()
    while size:
        b = stream.read(min(size, 1 << 22))
        h.update(b)
        size -= len(b)
    return h.digest()


img = open(image, 'rb')
base = None
for off in (0, 0x18300000, 0x0FD90000, 0x02080000):
    img.seek(off + 32 * 2048)
    v = img.read(28)
    if v[:20] == b'MICROSOFT*XBOX*MEDIA':
        base = off
        root_sector, root_size = struct.unpack('<II', v[20:28])
        break
if base is None:
    sys.exit(f'{image} is not an Xbox disc image')
disc = {}


def walk(sector, size, prefix):
    img.seek(base + sector * 2048)
    d = img.read(size)

    def node(pos):
        if pos + 14 > len(d):
            return
        left, right, s, z, attr, nl = struct.unpack('<HHIIBB', d[pos:pos + 14])
        if left == 0xFFFF:
            return
        if left:
            node(left * 4)
        name = prefix + d[pos + 14:pos + 14 + nl].decode('latin-1')
        if attr & 0x10:
            walk(s, z, name + '/')
        else:
            disc[name.lower()] = (s, z)
        if right:
            node(right * 4)
    node(0)


walk(root_sector, root_size, '')
s, z = disc['default.xbe']
img.seek(base + s * 2048)
disc_xbe = sha(img, z)

entries = []
for p in sorted(folder.rglob('*'), key=lambda p: p.relative_to(folder).as_posix().lower()):
    if not p.is_file():
        continue
    rel = p.relative_to(folder).as_posix()
    size = p.stat().st_size
    with open(p, 'rb') as f:
        digest = sha(f, size)
    on_disc = rel.lower() in disc and disc[rel.lower()][1] == size
    if on_disc:
        s, z = disc[rel.lower()]
        img.seek(base + s * 2048)
        on_disc = sha(img, z) == digest
    entries.append((rel, size, digest, 0 if on_disc else 1))

def c_bytes(b):
    return '{' + ','.join(str(x) for x in b) + '}'


out = ['/* generated by gen_manifest.py; do not edit. Sizes and SHA-256 only: no game data. */',
       '/* the disc\'s own default.xbe: Halo 2 (USA, Europe), the disc this build was made from */',
       f'static const unsigned char DISC_XBE_SHA256[32] = {c_bytes(disc_xbe)};',
       f'#define DISC_XBE_SIZE {disc["default.xbe"][1]}ULL',
       '/* from: 0 the disc, 1 title update 1.5 (the console\'s TDATA\\4D530064\\$u) */',
       'static const struct { const char *path; unsigned long long size; unsigned char sha256[32]; int from; } MANIFEST[] = {']
out += [f'    {{ "{r}", {s}ULL, {c_bytes(d)}, {w} }},' for r, s, d, w in entries]
out += ['};',
        f'#define MANIFEST_COUNT {len(entries)}',
        f'#define MANIFEST_BYTES {sum(s for _, s, _, _ in entries)}ULL',
        '']
Path(__file__).with_name('manifest.h').write_text('\n'.join(out), encoding='utf-8')
tu = [r for r, _, _, w in entries if w]
print(len(entries), 'files', sum(s for _, s, _, _ in entries), 'bytes; from the title update:', tu)
